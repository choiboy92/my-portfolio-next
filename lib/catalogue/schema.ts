import { z } from 'zod'

export const CATALOGUE_NOTICE = 'Generated by scripts/sync-apple-catalogue.ts from apple.com/uk. Do not edit by hand.'

const priceMapSchema = z.record(z.string(), z.number())

const appleCareTierSchema = z.object({
  name: z.string().min(1),
  price: z.number(),
  billing: z.enum(['monthly', 'annual']),
  partNumber: z.string().optional(),
})

const pencilSchema = z.object({
  pencilType: z.string(),
  price: z.number(),
})

const bandStyleSchema = z.object({
  styleName: z.string(),
  price: z.number(),
  bandColor: z.array(z.string()),
  bandSizeOptions: z.array(z.string()).optional(),
  bandSizesByCase: z.record(z.string(), z.array(z.string())).optional(),
  caseSizes: z.array(z.string()).optional(),
})

const bandGroupSchema = z.object({
  material: z.string(),
  style: z.array(bandStyleSchema),
})

const specSchema = z
  .strictObject({
    name: z.string().min(1),
    price: z.number().positive(),
    appleCare: z.array(appleCareTierSchema),
    partNumber: z.string().optional(),
    partNumbers: z.record(z.string(), z.string()).optional(),
    includes: z.array(z.string()).optional(),
    colors: z.array(z.string()).optional(),
    constraints: z
      .strictObject({
        minStorage: z.string().optional(),
        minMemory: z.string().optional(),
        minStorageForNanotexture: z.string().optional(),
      })
      .optional(),
    memoryOptions: priceMapSchema.optional(),
    storageOptions: priceMapSchema.optional(),
    chargerOptions: priceMapSchema.optional(),
    connectivityOptions: priceMapSchema.optional(),
    sizeOptions: priceMapSchema.optional(),
    nanoTexture: z.number().optional(),
    magicKeyboard: z.number().optional(),
    applePencil: z.array(pencilSchema).optional(),
    bandOptions: z.array(bandGroupSchema).optional(),
  })
  .refine(spec => new Set(spec.appleCare.map(tier => tier.name)).size === spec.appleCare.length, {
    message: 'AppleCare tier names must be unique within a spec',
    path: ['appleCare'],
  })

const modelSchema = z.object({
  displayName: z.string(),
  colors: z.array(z.string()),
  specs: z.array(specSchema).min(1),
})

const categorySchema = z.object({
  category: z.string(),
  models: z.record(z.string(), modelSchema),
})

export const catalogueSchema = z.object({
  notice: z.literal(CATALOGUE_NOTICE),
  categories: z.object({
    iPhone: categorySchema,
    iPad: categorySchema,
    MacBook: categorySchema,
    'Apple Watch': categorySchema,
  }),
})

export type Catalogue = z.infer<typeof catalogueSchema>
export type CategoryKey = keyof Catalogue['categories']
export type Category = z.infer<typeof categorySchema>
export type Model = z.infer<typeof modelSchema>
export type Spec = z.infer<typeof specSchema>
export type AppleCareTier = z.infer<typeof appleCareTierSchema>
export type Pencil = z.infer<typeof pencilSchema>
export type BandGroup = z.infer<typeof bandGroupSchema>
export type BandStyle = z.infer<typeof bandStyleSchema>
export type PriceMap = z.infer<typeof priceMapSchema>

export function parseCatalogue(data: unknown): Catalogue {
  return catalogueSchema.parse(data)
}
